/**
 * The modern clipboard API only works on https or localhost. The phone dev URL
 * (http://<laptop-ip>:3000) is neither, so copying falls back to the older method.
 */

export async function copyText(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // fall through to the fallback
  }
  try {
    const ta = document.createElement("textarea");
    ta.value = text;
    ta.setAttribute("readonly", "");
    ta.style.position = "fixed";
    ta.style.top = "0";
    ta.style.opacity = "0";
    document.body.appendChild(ta);
    ta.select();
    ta.setSelectionRange(0, text.length);
    const ok = document.execCommand("copy");
    ta.remove();
    return ok;
  } catch {
    return false;
  }
}

export function canReadClipboard(): boolean {
  return typeof window !== "undefined" && window.isSecureContext && !!navigator.clipboard?.readText;
}
